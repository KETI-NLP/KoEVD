"""Regression for the provider attribute omitted in the failed HF activation."""
import importlib.util
from pathlib import Path
import tempfile
import unittest


class ContextLFSTests(unittest.TestCase):
    def setUp(self):
        temporary=tempfile.TemporaryDirectory();self.addCleanup(temporary.cleanup)
        self.root=Path(temporary.name);self.base=self.root/'base';self.out=self.root/'out'
        self.base.mkdir();(self.out/'operator-data').mkdir(parents=True)
        path=Path(__file__).resolve().parents[1]/'scripts/materialize_public_space.py'
        spec=importlib.util.spec_from_file_location('public_context_lfs',path)
        self.module=importlib.util.module_from_spec(spec);spec.loader.exec_module(self.module)
        with (self.out/'operator-data/core-index.json').open('wb') as stream:
            stream.seek(10_000_000);stream.write(b'\n')

    def test_large_asset_filter_survives_context_and_preserves_existing_provider_rules(self):
        prior=b'*.bin filter=lfs diff=lfs merge=lfs -text\n'
        (self.base/'.gitattributes').write_bytes(prior)
        self.module.preserve_lfs_attributes(self.base,self.out)
        actual=(self.out/'.gitattributes').read_bytes()
        self.assertTrue(actual.startswith(prior))
        self.assertIn(b'operator-data/core-index.json filter=lfs diff=lfs merge=lfs -text\n',actual)
        (self.base/'.gitattributes').write_bytes(actual)
        self.module.preserve_lfs_attributes(self.base,self.out)
        self.assertEqual((self.out/'.gitattributes').read_bytes(),actual)

    def test_fresh_context_does_not_depend_on_provider_autogenerated_attributes(self):
        self.module.preserve_lfs_attributes(self.base,self.out)
        self.assertEqual((self.out/'.gitattributes').read_text(encoding='utf-8'),
            'operator-data/core-index.json filter=lfs diff=lfs merge=lfs -text\n')
